/**
 * 장비 도감.
 *
 * 지금까지의 장비는 단색 실루엣이었다. 그건 대시보드에서는 옳다 — 테마를 따라가야
 * 하니까. 하지만 펫은 게임 UI 이고, 게임 아이템이 아이템처럼 보이는 이유는
 * **외곽선 + 3~4톤 음영**이다. 그래서 여기서는 아이템마다 자기 팔레트를 갖는다.
 *
 * 그리는 방법: 24×24 문자 그리드 한 장이 아이템 하나다. 문자는 팔레트 인덱스이고
 * `.` 은 투명. 좌표를 손으로 세는 대신 그림을 그대로 보면서 고칠 수 있다 —
 * 픽셀아트에서 제일 중요한 건 도구가 아니라 **눈으로 보면서 고칠 수 있는가**다.
 *
 *   node make-items.mjs
 */

import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "renderer", "assets");
const CELL = 2; // 24 그리드 → 48 뷰박스

/** 그리드 + 팔레트 → SVG. 같은 색이 가로로 이어지면 한 사각형으로 합친다. */
function draw(rows, palette) {
  const out = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (c === "." || !palette[c]) {
        x += 1;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === c) w += 1;
      out.push(
        `<rect x="${x * CELL}" y="${y * CELL}" width="${w * CELL}" height="${CELL}" fill="${palette[c]}"/>`,
      );
      x += w;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" version="1.1" viewBox="0 0 48 48" shape-rendering="crispEdges">${out.join("")}</svg>\n`;
}

